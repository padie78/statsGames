function metric(
  partial: Omit<ObjectiveMetricType, 'higherIsBetter'> & { higherIsBetter?: boolean },
): ObjectiveMetricType {
  return {
    ...partial,
    higherIsBetter: partial.higherIsBetter ?? partial.goalKind === 'at_least',
  };
}

